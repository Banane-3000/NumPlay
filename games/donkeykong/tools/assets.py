def rows(name):
    art = ART[name]
    width = max(map(len, art))
    return [row.ljust(width, '.') for row in art]

def main():
    result = ['/* SPDX-License-Identifier: GPL-3.0-only; generated by tools/assets.py */',
              'typedef struct {uint8_t w,h;const uint8_t *p;} dk_sprite;']
    result.append('static const uint16_t palette[]={' + ','.join(
        str(((c >> 8) & 0xF800) | ((c >> 5) & 0x7E0) | ((c >> 3) & 31)) for c in COLORS) + '};')
    for name in ART:
        art = rows(name)
        values = [0 if ch == '.' else int(ch, 16) for row in art for ch in row]
        if len(values) % 2:
            values.append(0)
        data = [values[i] << 4 | values[i+1] for i in range(0, len(values), 2)]
        result.append('static const uint8_t pixels_' + name + '[]={' + ','.join(map(str, data)) + '};')
        result.append(f'static const dk_sprite spr_{name}={{{len(art[0])},{len(art)},pixels_{name}}};')
    (ROOT/'src/assets.h').write_text('\n'.join(result)+'\n')
    # A tiny arcade cabinet icon: ape, red girders and blue ladders.
    pixels = [[COLORS[0]]*55 for _ in range(56)]
    for y in (6, 38, 50):
        for x in range(3, 52):
            pixels[y][x] = COLORS[1]
            pixels[y+3][x] = COLORS[9]
            if x%6 < 2:
                pixels[y+1][x] = pixels[y+2][x] = COLORS[9]
    for y in range(41, 50):
        for x in (9, 15, 39, 45):
            pixels[y][x] = COLORS[10]
        if y%3 == 0:
            for x in list(range(9, 16))+list(range(39, 46)):
                pixels[y][x] = COLORS[10]
    for y, row in enumerate(rows('kong')):
        for x, ch in enumerate(row):
            if ch != '.':
                pixels[y+11][x+14] = COLORS[int(ch,16)]
    raw = b''.join(b'\0'+b''.join(bytes((c >> 16, c >> 8 & 255, c & 255)) for c in row) for row in pixels)
    def chunk(kind, data):
        return struct.pack('>I',len(data))+kind+data+struct.pack('>I',zlib.crc32(kind+data))
    png = b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',55,56,8,2,0,0,0))
    png += chunk(b'IDAT',zlib.compress(raw,9))+chunk(b'IEND',b'')
    (ROOT/'src/icon.png').write_bytes(png)

if __name__ == '__main__':
    main()
