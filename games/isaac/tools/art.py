def art(rows, pal):
    """rows of characters -> RGBA, '.' transparent"""
    h, w = len(rows), max(len(r) for r in rows)
    im = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch in pal:
                c = pal[ch]
                im.putpixel((x, y), tuple(c) + ((255,) if len(c) == 3 else ()))
    return im


