def door(kind, open_):
    """a door in the top wall, at the game's size (the room's 26-pixel cells): 52 wide, 40 deep; the floor's
    side is its bottom. The other three walls turn it."""
    w, h = 52, 40
    im = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    frames = {"normal": ((92, 74, 66), (60, 46, 42), (130, 108, 96)),
              "treasure": ((222, 170, 40), (150, 100, 20), (255, 230, 120)),
              "boss": ((140, 20, 20), (70, 10, 10), (200, 60, 50)),
              "secret": ((70, 60, 54), (40, 34, 30), (90, 80, 72)),
              "shop": ((120, 90, 60), (70, 50, 30), (170, 130, 90)),
              "curse": ((110, 20, 26), (50, 8, 10), (160, 40, 40)),
              "devil": ((40, 10, 10), (20, 4, 4), (110, 20, 20)),
              "angel": ((230, 230, 240), (170, 170, 190), (255, 255, 255)),
              "arcade": ((200, 60, 140), (110, 30, 80), (250, 140, 200))}
    face, dark, light = frames[kind]
    if kind == "secret":   # a hole blown in the wall
        d.ellipse([10, 6, 42, 40], fill=(16, 10, 8, 255))
        d.ellipse([14, 10, 38, 40], fill=(4, 2, 2, 255))
        for x, y in ((8, 10), (40, 12), (12, 30), (38, 32), (26, 4)):
            d.ellipse([x - 3, y - 2, x + 3, y + 2], fill=(60, 50, 44, 255))
        return im
    # the frame: an arch with its sides
    d.polygon([(4, 0), (48, 0), (46, 38), (6, 38)], fill=dark + (255,))
    d.polygon([(7, 2), (45, 2), (43, 36), (9, 36)], fill=face + (255,))
    d.line([(8, 3), (44, 3)], fill=light + (255,), width=2)
    # the opening
    d.polygon([(14, 4), (38, 4), (37, 38), (15, 38)], fill=(8, 4, 4, 255))
    if not open_:   # two door halves, shut
        leaf = (88, 64, 50) if kind not in ("treasure", "angel") else (200, 160, 60)
        if kind == "boss":
            leaf = (90, 24, 20)
        d.rectangle([15, 8, 25, 37], fill=leaf + (255,))
        d.rectangle([27, 8, 36, 37], fill=leaf + (255,))
        d.line([(26, 8), (26, 37)], fill=(20, 10, 8, 255))
        for y in (14, 24, 33):
            d.line([(15, y), (36, y)], fill=(40, 26, 20, 255))
    if kind == "boss":   # its spikes and eyes
        for x in (6, 14, 38, 46):
            d.polygon([(x - 3, 0), (x + 3, 0), (x, -0 + 6)], fill=(230, 220, 200, 255))
        d.ellipse([18, 0, 24, 5], fill=(255, 230, 120, 255))
        d.ellipse([28, 0, 34, 5], fill=(255, 230, 120, 255))
    if kind == "treasure":
        d.polygon([(22, 0), (26, -0), (24, 4)], fill=(255, 250, 200, 255))
    if kind == "curse":
        for x in (8, 16, 36, 44):
            d.polygon([(x - 3, 38), (x + 3, 38), (x, 30)], fill=(220, 210, 190, 255))
    return im


