# ---------------------------------------------------------------- the HUD (drawn at the screen's size)
HEART = [
    "..###.###..",
    ".#aaa#aaa#.",
    "#aawaaaaaa#",
    "#awaaaaaaa#",
    "#aaaaaaaaa#",
    ".#aaaaaaa#.",
    "..#aaaaa#..",
    "...#aaa#...",
    "....#a#....",
    ".....#.....",
]
HEARTS = {"red": (210, 30, 30), "soul": (110, 140, 205), "black": (40, 36, 44), "eternal": (250, 250, 250),
          "empty": (40, 16, 16)}


def heart(kind, half=False):
    """a HUD heart: full, or its left half (the right one an empty container)"""
    rows = [list(r) for r in HEART]
    pal = {"#": (0, 0, 0), "a": HEARTS[kind], "w": (255, 255, 255) if kind != "eternal" else (200, 200, 220),
           "e": HEARTS["empty"]}
    if kind == "black":
        pal["w"] = (100, 90, 110)
    if half:
        for r in rows:
            for x in range(6, len(r)):
                if r[x] in "aw":
                    r[x] = "e" if kind == "red" else "."
            if kind != "red":   # soul and black halves are the left half alone
                for x in range(6, len(r)):
                    if r[x] == "#" and (x > 6 and "." in r[x - 1:x]):
                        r[x] = "."
        if kind != "red":
            rows = [r[:6] + ["#" if r[5] in "aw#" and ch != "." else "." for ch in r[6:7]] + ["."] * 4 for r in rows]
            rows[0][6] = "."
    return art(["".join(r) for r in rows], pal)


