"""Build small, shared-palette sprites from the user-supplied AlexDer ZIP.

python tools/assets.py '/path/to/Uno Game Assets (1).zip'
No original-size textures, PDF, fonts or executable files are shipped.
"""
import argparse, hashlib, io, json, zipfile
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
W, H = 44, 64

def array(name, kind, data, columns=24):
    return 'static const '+kind+' '+name+'[] = {\n'+''.join(
        '  '+','.join(str(x) for x in data[i:i+columns])+',\n' for i in range(0,len(data),columns))+'};\n'

def main():
    p=argparse.ArgumentParser(); p.add_argument('zip',type=Path); a=p.parse_args()
    names=[f'{c}_{v}.png' for c in ('Red','Yellow','Green','Blue')
           for v in list(map(str,range(10)))+['Skip','Reverse','Draw']]+['Wild.png','Wild_Draw.png','Deck.png']
    with zipfile.ZipFile(a.zip) as z:
        members={Path(n).name:n for n in z.namelist() if n.startswith('Uno Game Assets/') and n.endswith('.png')}
        def read(n): return Image.open(io.BytesIO(z.read(members[n]))).convert('RGBA')
        images=[read(n).resize((W,H),Image.Resampling.LANCZOS) for n in names]
        sample=Image.new('RGB',(W*len(images),H),'white')
        for i,im in enumerate(images): sample.paste(im,(i*W,0),im)
        pal=sample.quantize(colors=31,method=Image.Quantize.MEDIANCUT)
        colors=pal.getpalette()[:93]
        palette=[((colors[i]&248)<<8)|((colors[i+1]&252)<<3)|(colors[i+2]>>3) for i in range(0,93,3)]
        encoded=bytearray(); offsets=[]
        for im in images:
            offsets.append(len(encoded))
            rgb=Image.new('RGB',im.size,'white');rgb.paste(im,mask=im.getchannel('A'))
            ix=list(rgb.quantize(palette=pal,dither=Image.Dither.NONE).getdata());alpha=list(im.getchannel('A').getdata())
            ix=[v if alpha[i]>=128 else 31 for i,v in enumerate(ix)]
            for y in range(H):
                row=ix[y*W:(y+1)*W]; tokens=[];x=0
                while x<W:
                    n=1
                    while x+n<W and row[x+n]==row[x] and n<8:n+=1
                    tokens.append(((n-1)<<5)|row[x]);x+=n
                encoded.append(len(tokens)); encoded.extend(tokens)
        offsets.append(len(encoded))
        table=read('Table_2.png').convert('RGB').resize((32,24),Image.Resampling.LANCZOS)
        packed=[((r&248)<<8)|((g&252)<<3)|(b>>3) for r,g,b in table.getdata()]
        content='/* Generated by tools/assets.py. AlexDer card art, see ASSETS.md. */\n#define CARD_W 44\n#define CARD_H 64\n'
        content+=array('card_palette','uint16_t',palette)+array('card_offsets','uint16_t',offsets)
        content+=array('card_pixels','uint8_t',list(encoded))+array('table_pixels','uint16_t',packed)
        (ROOT/'src/assets.h').write_text(content,encoding='utf-8')
        icon=Image.new('RGBA',(55,56),(15,47,41,255))
        for name,x,y in [('Red_7.png',3,7),('Wild.png',17,3),('Deck.png',31,7)]:
            im=read(name).resize((23,34),Image.Resampling.LANCZOS);icon.alpha_composite(im,(x,y+6))
        icon.save(ROOT/'src/icon.png')
        report=dict(source_sha256=hashlib.sha256(a.zip.read_bytes()).hexdigest(),cards=55,width=W,height=H,
                    card_rom_bytes=len(encoded)+2*len(offsets)+2*len(palette),table_rom_bytes=len(packed)*2)
        (ROOT/'tools/assets.json').write_text(json.dumps(report,indent=2)+'\n')
        print(json.dumps(report,indent=2))

if __name__=='__main__':main()
